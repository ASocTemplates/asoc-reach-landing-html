/**
 * `node build/progress.js` — regenerate PROGRESS.md.
 *
 * Marketing edition (Option A — repointed at `marketingNav`, not removed; see
 * this repo's CLAUDE.md). `navGroups` is `[]` here — the admin sidebar tree
 * doesn't apply — so the stock version of this script would silently report
 * "0/0 done" against nothing, which looks like a passing completeness check
 * without being one. Cross-references every href in `marketingNav.header` +
 * `marketingNav.footer` against the files in `pages/` instead, resolving
 * `/#anchor` links to the page they land on (there's no way to verify a `#id`
 * exists inside an unrendered fragment, only that its page does).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { marketingNav } from "../src/nav.config.js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const pagesDir = path.join(root, "pages");

const pagePath = (href) => href.replace(/^\//, "").replace(/#.*$/, "") || "index";
const exists = (href) => fs.existsSync(path.join(pagesDir, `${pagePath(href)}.html`));

const rows = [];
const seen = new Set();
for (const item of marketingNav.header) {
  if (seen.has(item.href)) continue;
  seen.add(item.href);
  rows.push({ group: "Header", title: item.title, href: item.href, done: exists(item.href) });
}
for (const col of marketingNav.footer) {
  for (const item of col.links) {
    if (seen.has(item.href)) continue;
    seen.add(item.href);
    rows.push({ group: `Footer — ${col.label}`, title: item.title, href: item.href, done: exists(item.href) });
  }
}

// Pages that exist but are reachable from neither header nor footer nav
// (auth, error pages, and content-only pages linked from within a section,
// like materialised dynamic-route items).
const offNav = [];
const walk = (dir, prefix = "") => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) walk(path.join(dir, entry.name), `${prefix}/${entry.name}`);
    else if (entry.name.endsWith(".html")) {
      const href = `${prefix}/${entry.name.replace(/\.html$/, "")}`;
      const bare = href.replace(/\/index$/, "") || "/";
      if (!rows.some((r) => pagePath(r.href) === entry.name.replace(/\.html$/, "") || `/${pagePath(r.href)}` === bare))
        offNav.push(href);
    }
  }
};
walk(pagesDir);

const done = rows.filter((r) => r.done).length;
const lines = [
  "# Port progress",
  "",
  "Generated by `node build/progress.js` — do not edit by hand.",
  "",
  `**Nav links: ${done} / ${rows.length} resolved.** Plus ${offNav.length} off-nav pages ` +
    "(reachable by direct link from within a section, not from marketingNav).",
  "",
];

let current = null;
for (const row of rows) {
  if (row.group !== current) {
    current = row.group;
    lines.push("", `## ${current}`, "");
  }
  lines.push(`- [${row.done ? "x" : " "}] \`${row.href}\` — ${row.title}`);
}

lines.push("", "## Off-nav pages", "", ...offNav.sort().map((h) => `- [x] \`${h}\``), "");
fs.writeFileSync(path.join(root, "PROGRESS.md"), lines.join("\n"));
console.log(`PROGRESS.md: ${done}/${rows.length} nav links resolved, ${offNav.length} off-nav.`);
